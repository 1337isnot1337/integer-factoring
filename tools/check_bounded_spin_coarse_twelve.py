#!/usr/bin/env python3
"""Twelve-site coarse spectrum of the replica swap and transposition class sum.

The full twelve-site coefficient algebra is expensive.  The smaller
subalgebra generated by the replica swap R and the compressed diagonal
transposition class sum T still gives a useful partition of the 7921-state
module.  This checker records that partition and its six joint generalized
eigenspaces.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from check_bounded_spin_transposition_subalgebra import (
    frame, nullity, replica_swap, transposition_class_sum,
    transposition_matrices,
)
from native_gf5_flint import multiply, rank

PRIME = 5
ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / 'evidence/bounded-spin-coarse-twelve.json'
EXPECTED = {
    (0, 1): 1320, (0, 4): 165,
    (1, 1): 2015, (1, 4): 1266,
    (4, 1): 670, (4, 4): 2485,
}


def sixth_power(mat: np.ndarray, value: int) -> np.ndarray:
    identity = np.eye(len(mat), dtype=np.int64)
    a = (mat.astype(np.int64) - value * identity) % PRIME
    a2 = multiply(a, a)
    a4 = multiply(a2, a2)
    return multiply(a4, a2)


def coarse_dimensions(length: int = 12) -> dict[tuple[int, int], int]:
    ps, words, vectors, inverse_norms = frame(length)
    q = len(ps)
    matrices = transposition_matrices(length, words, vectors, inverse_norms)
    b = transposition_class_sum(matrices)
    r = replica_swap(q)
    identity = np.eye(len(b), dtype=np.int64)
    result = {}
    for value in range(PRIME):
        power = sixth_power(b, value)
        for sign in (1, PRIME - 1):
            space = nullity(np.vstack((power, (r.astype(np.int64) - sign * identity) % PRIME)))
            if space:
                result[value, sign] = space
    assert sum(result.values()) == q * q
    return result


def check_evidence() -> dict:
    receipt = json.loads(EVIDENCE.read_text())
    recorded = {(int(a), int(b)): value for a, b, value in receipt['coarse_dimensions']}
    assert recorded == EXPECTED
    assert sum(recorded.values()) == 89 * 89
    assert receipt['length'] == 12 and receipt['paths'] == 89
    return {'passed': True,
            'coarse_dimensions': [[a, b, value] for (a, b), value in sorted(recorded.items())],
            'sum': sum(recorded.values()), 'scope': receipt['scope']}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--recompute', action='store_true',
                        help='rebuild the twelve-site module (about two hours)')
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    if args.recompute:
        dimensions = coarse_dimensions(12)
        recorded = {f'{a},{b}': value for (a, b), value in sorted(dimensions.items())}
        receipt = {'length': 12, 'paths': 89,
                   'coarse_dimensions': recorded,
                   'scope': ('Twelve-site replica-swap and transposition class '
                             'sum coarse joint generalized dimensions.')}
        if args.output:
            args.output.write_text(json.dumps(receipt, indent=2) + '\n')
        print(json.dumps(receipt, indent=2))
        return
    print(json.dumps(check_evidence(), indent=2))


if __name__ == '__main__':
    main()
