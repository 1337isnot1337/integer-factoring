#!/usr/bin/env python3
"""Measure the cofactor predicate on complete, certified cyclic orbits.

The finite checks do not establish a uniform density or moment estimate.
All averages use the subgroup generated by the specific recorded form.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from math import gcd, prod
from pathlib import Path

from binary_quadratic_forms import reduce_form
from cofactor_ideal_closure import factor_with_cofactor_ideal_closure
from leading_power_smooth_relations import compose_with_prime_form
from prime_form_factor_base import build_prime_form_factor_base
from quadratic_ideal_hnf import compose_forms_hnf


def ceiling_root(integer: int, degree: int) -> int:
    if integer < 1 or degree < 1:
        raise ValueError("Require positive integer and degree")
    low, high = 0, 1 << ((integer.bit_length() + degree - 1) // degree)
    while high - low > 1:
        middle = (low + high) // 2
        if middle ** degree >= integer:
            high = middle
        else:
            low = middle
    assert (high - 1) ** degree < integer <= high ** degree
    return high


def cyclic_window_counts(flags: bytes, window: int) -> list[int]:
    period, good = len(flags), sum(flags)
    whole, remainder = divmod(window, period)
    current = whole * good + sum(flags[:remainder])
    counts = []
    for phase in range(period):
        counts.append(current)
        current += flags[(phase + remainder) % period] - flags[phase]
    assert sum(counts) == good * window
    return counts


def moment_record(flags: bytes, order: int, window: int, constant: int = 1,
                  *, counts: list[int] | None = None) -> dict:
    """Check E|A-delta W|^(2q) <= (C q W delta)^q with integers."""
    if not flags or not sum(flags) or min(order, window, constant) < 1:
        raise ValueError("Require a nonempty good set and positive parameters")
    period, good = len(flags), sum(flags)
    if counts is None:
        counts = cyclic_window_counts(flags, window)
    assert len(counts) == period and sum(counts) == good * window
    deviations = [period * count - good * window for count in counts]
    numerator = sum(value ** (2 * order) for value in deviations)
    lower_numerator = sum((-value) ** (2 * order) for value in deviations if value < 0)
    unit_bound = period ** (order + 1) * (order * window * good) ** order
    bound = constant ** order * unit_bound
    required = max(1, ceiling_root(max(1, (numerator + unit_bound - 1) // unit_bound), order))
    lower_required = max(1, ceiling_root(max(1, (lower_numerator + unit_bound - 1) // unit_bound), order))
    assert numerator <= required ** order * unit_bound
    assert required == 1 or numerator > (required - 1) ** order * unit_bound
    assert lower_numerator <= lower_required ** order * unit_bound
    assert lower_required == 1 or lower_numerator > (lower_required - 1) ** order * unit_bound
    maximum_lower_deviation = max(0, good * window - period * min(counts))
    assert ((2 * order + 1) * period * lower_numerator
            >= maximum_lower_deviation ** (2 * order + 1))
    return {"moment_order": order, "window": window, "constant": constant,
            "minimum_hits": min(counts), "maximum_hits": max(counts),
            "centered_scaled_sum": numerator, "constant_one_scaled_bound": unit_bound,
            "moment_bound_holds": numerator <= bound,
            "least_positive_integer_constant": required,
            "lower_tail_scaled_sum": lower_numerator,
            "lower_tail_moment_bound_holds": lower_numerator <= bound,
            "lower_tail_least_positive_integer_constant": lower_required}


def maximum_zero_run(flags: bytes) -> int:
    if not flags or not sum(flags):
        raise ValueError("Require a nonempty good set")
    first = flags.index(1)
    longest = current = 0
    for offset in range(1, len(flags) + 1):
        if flags[(first + offset) % len(flags)]:
            current = 0
        else:
            current += 1
            longest = max(longest, current)
    return longest


def sufficient_moment_window(period_bound: int, density_denominator: int,
                             order: int, constant: int = 1) -> int:
    """The exact conditional bound using the window-count Lipschitz estimate."""
    if min(period_bound, density_denominator, order, constant) < 1:
        raise ValueError("Require positive moment parameters")
    threshold = (2 * order + 1) * (constant * order) ** order * period_bound
    return density_denominator * (ceiling_root(threshold, order + 1) + 1)


def actual_orbit(integer: int, cutoff: int, cap: int, generator: dict,
                 period_cap: int) -> tuple[dict, bytes | None]:
    delta = -integer if integer % 4 == 3 else -4 * integer
    identity = (1, delta % 2, (delta % 2 - delta) // 4)
    base = build_prime_form_factor_base(delta, cutoff)
    records = {item.prime: (item.root, item.positive) for item in base["records"]}
    if integer % 4 == 1:
        records[2] = (2, reduce_form((2, 2, (integer + 1) // 2)))
    prime_product = prod(records)
    form = tuple(generator["form"])
    target, flags = identity, bytearray()
    leading_gcd_hits = 0
    for _ in range(period_cap):
        divisor = gcd(target[0], integer)
        gcd_hit = 1 < divisor < integer
        leading_gcd_hits += gcd_hit
        residual = target[0] // gcd(target[0], pow(prime_product, target[0].bit_length(), target[0]))
        flags.append(int(gcd_hit or residual <= cap))
        if generator["kind"] == "prime":
            prime = generator["norm"]
            target = compose_with_prime_form(target, prime, *records[prime])
        else:
            target = compose_forms_hnf(target, form)
        if target == identity:
            break
    record = {"integer": integer, "input_bits": integer.bit_length(), "cutoff": cutoff,
              "max_cofactor": cap, "generator": generator,
              "complete_period": target == identity,
              "enumerated_classes": len(flags), "leading_gcd_hits": leading_gcd_hits}
    if target != identity:
        return record, None
    flags = bytes(flags)
    assert flags[0] == 1
    assert all(flags[index] == flags[-index] for index in range(len(flags)))
    record.update({"period": len(flags), "good_classes": sum(flags),
                   "maximum_inadmissible_gap": maximum_zero_run(flags),
                   "predicate_sha256": hashlib.sha256(flags).hexdigest(),
                   "inverse_symmetry_checked": True})
    return record, flags


def profile_orbit(record: dict, flags: bytes) -> dict:
    period, good = len(flags), sum(flags)
    order = (record["input_bits"] + 1).bit_length()
    density_denominator = (period + good - 1) // good
    root = ceiling_root(period, order)
    window = 2 * order * density_denominator * root
    theorem = moment_record(flags, order, window)
    if theorem["moment_bound_holds"]:
        assert theorem["minimum_hits"] >= 1
    record.update({"density_denominator_bound": density_denominator,
                   "theorem_period_root": root, "uses_certified_actual_period": True,
                   "elementary_window_check": theorem})
    sufficient_windows = []
    for period_bound in (period, 2 * record["integer"]):
        for constant in (1, 2, 4, 8):
            width = sufficient_moment_window(period_bound, density_denominator, order, constant)
            check = moment_record(flags, order, width, constant)
            if check["lower_tail_moment_bound_holds"]:
                assert check["minimum_hits"] >= 1
            check.update({"period_bound": period_bound,
                          "period_bound_is_input_only": period_bound == 2 * record["integer"]})
            sufficient_windows.append(check)
    record["lipschitz_conditional_windows"] = sufficient_windows
    windows = set()
    power = 1
    while power < period:
        windows.add(power)
        power *= 2
    windows.update((period, max(1, period // 3), max(1, period // 2),
                    max(1, maximum_zero_run(flags))))
    moments = []
    for width in sorted(windows):
        counts = cyclic_window_counts(flags, width)
        for moment_order in sorted({1, 2, 4, order}):
            moments.append(moment_record(flags, moment_order, width, counts=counts))
    record["moment_profile"] = moments
    record["maximum_required_integer_constant"] = max(
        item["least_positive_integer_constant"] for item in moments)
    record["maximum_lower_tail_required_integer_constant"] = max(
        item["lower_tail_least_positive_integer_constant"] for item in moments)
    # The exact second-moment identity is checked independently at short widths.
    correlations = [sum(flags[index] * flags[(index + shift) % period]
                        for index in range(period)) for shift in range(min(32, period))]
    for width in range(1, min(32, period) + 1):
        counts = cyclic_window_counts(flags, width)
        numerator = sum((period * count - good * width) ** 2 for count in counts)
        covariance_numerator = width * good * (period - good)
        covariance_numerator += 2 * sum((width - shift) * (period * correlations[shift] - good * good)
                                        for shift in range(1, width))
        assert numerator == period * covariance_numerator
    record["short_pair_overlap_counts"] = correlations
    return record


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    parser.add_argument("--period-cap", type=int, default=1_000_000)
    args = parser.parse_args()
    roots = 0
    for integer in range(1, 300):
        for degree in range(1, 10):
            ceiling_root(integer, degree)
            roots += 1
    abstract = bytes(int((index * 37 + index // 7) % 11 < 6) for index in range(512))
    denominator = (len(abstract) + sum(abstract) - 1) // sum(abstract)
    abstract_window = 2 * 5 * denominator * ceiling_root(len(abstract), 5)
    abstract_check = moment_record(abstract, 5, abstract_window)
    assert abstract_window < len(abstract)
    assert abstract_check["moment_bound_holds"] and abstract_check["minimum_hits"] > 0
    abstract_check.update({"period": len(abstract), "good_classes": sum(abstract),
                           "maximum_inadmissible_gap": maximum_zero_run(abstract)})
    lipschitz_checks = 0
    for period in (7, 11, 17, 32, 63):
        for good in range(1, period, max(1, period // 9)):
            # Clustered sets supply genuine empty windows and do not satisfy
            # an unjustified independence assumption.
            flags = bytes([1] * good + [0] * (period - good))
            for width in sorted({1, max(1, (period - good) // 2), period - good}):
                counts = cyclic_window_counts(flags, width)
                assert min(counts) == 0 and width < period
                for order in (1, 2, 3, 5):
                    check = moment_record(flags, order, width, counts=counts)
                    assert ((2 * order + 1) * period * check["centered_scaled_sum"]
                            >= (good * width) ** (2 * order + 1))
                    lipschitz_checks += 1
    cases = []
    specifications = ((1009 * 1013, 5, 100), (10007 * 10009, 7, 1000),
                      (1000003 * 1000033, 19, 10000))
    for integer, cutoff, cap in specifications:
        delta = -integer if integer % 4 == 3 else -4 * integer
        base = build_prime_form_factor_base(delta, cutoff)
        generators = [{"kind": "prime", "norm": item.prime, "form": item.positive}
                      for item in base["records"][:2]]
        closure = factor_with_cofactor_ideal_closure(integer, cutoff, 32,
                    max_cofactor=cap, max_generators=256, max_queries=10000)
        residuals = [item for item in closure["generators"] if item["kind"] == "residual"][:2]
        generators += [{key: item[key] for key in ("kind", "norm", "form", "key")}
                       for item in residuals]
        for generator in generators:
            record, flags = actual_orbit(integer, cutoff, cap, generator, args.period_cap)
            if flags is not None:
                profile_orbit(record, flags)
            cases.append(record)
    result = {"claim": "Exact finite cyclic-orbit cofactor densities, gaps, and centered moments",
              "predicate": "proper leading-norm gcd OR residual after fixed-base saturation <= cap",
              "scope": "Complete individual cyclic subgroups only; no uniform density or moment theorem is claimed.",
              "ceiling_root_checks": roots, "abstract_nontrivial_window_control": abstract_check,
              "empty_window_lipschitz_lower_bound_controls": lipschitz_checks,
              "complete_orbits": sum(case["complete_period"] for case in cases),
              "incomplete_orbits": sum(not case["complete_period"] for case in cases),
              "cases": cases}
    text = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.write_text(text)
    print(text, end="")


if __name__ == "__main__":
    main()
