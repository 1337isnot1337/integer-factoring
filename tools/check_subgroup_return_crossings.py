#!/usr/bin/env python3
"""Replay complete finite coefficient spans of two subgroup-return crossings."""
from __future__ import annotations

import argparse
from hashlib import sha256
from itertools import product
import json
from pathlib import Path

from check_controlled_permutation_smith import binary_rank
from subgroup_return_crossings import (FAMILIES, FIRST, PERMUTATIONS, SECOND,
                                      coefficient_rows, reduce_word, subgroup_return)

ROOT = Path(__file__).resolve().parents[1]
THRESHOLDS = {'free-commutator': (24, 576, 102960), 'four-state': (24, 576, 188136)}


def rank_pairs(cuts, low=False):
    size, degree = len(cuts[0][0]), len(cuts[0])
    current, previous = [[0]*size for _ in range(2)], 0
    ranks = [(0, 0)]*(1 << degree)
    for index in range(1, len(ranks)):
        mask = index ^ (index >> 1)
        changed = (mask ^ previous).bit_length()-1
        current = [[a ^ b for a, b in zip(old, side[changed])]
                   for old, side in zip(current, cuts)]
        previous = mask
        ranks[mask] = tuple(binary_rank(a, low=low) for a in current)
    return ranks


def upper_path(ranks, threshold):
    basis = {}
    for mask, (r, c) in enumerate(ranks):
        if r*c > threshold:
            continue
        value, representation = mask, 1 << mask
        while value:
            pivot = value.bit_length()-1
            if pivot not in basis:
                basis[pivot] = value, representation
                break
            a, b = basis[pivot]
            value, representation = value ^ a, representation ^ b
    value, representation = len(ranks)-1, 0
    while value:
        a, b = basis[value.bit_length()-1]
        value, representation = value ^ a, representation ^ b
    return [i for i in range(len(ranks)) if representation >> i & 1]


def generate():
    records = []
    for family in FAMILIES:
        for length in (1, 2, 3):
            cuts, support = coefficient_rows(length, family)
            ranks = rank_pairs(cuts)
            threshold = THRESHOLDS[family][length-1]
            records.append(dict(family=family, length=length, support=support, ranks=ranks,
                                detector=1 << (3 if length < 3 else 5),
                                threshold=threshold, upper_path=upper_path(ranks, threshold)))
    names = ('subgroup_return_crossings.py', 'check_subgroup_return_crossings.py',
             'check_steiner_cubic_crossings.py')
    return dict(records=records,
                source_sha256={name: sha256((ROOT/'tools'/name).read_bytes()).hexdigest()
                               for name in names},
                scope='All F2 coefficient masks at lengths one, two and three for two stated filters.',
                factoring_exponent='1/2; unchanged')


def language_controls():
    # Independent adjacent-cancellation algorithm and the folded four-cycle
    # for the subgroup generated by a b a^-1 b^-1.
    graph = {(0, 1): 1, (1, 2): 2, (2, -1): 3, (3, -2): 0,
             (1, -1): 0, (2, -2): 1, (3, 1): 2, (0, 2): 3}
    count = 0
    for length in range(9):
        for word in product((1, 2, -1, -2), repeat=length):
            reduced = list(word)
            index = 0
            while index+1 < len(reduced):
                if reduced[index] == -reduced[index+1]:
                    del reduced[index:index+2]
                    index = max(0, index-1)
                else:
                    index += 1
            assert tuple(reduced) == reduce_word(word)
            vertex = 0
            for letter in reduced:
                vertex = graph.get((vertex, letter), -1)
            assert (vertex == 0) == subgroup_return(word, 'free-commutator')
            count += 1
    assert count == 87381
    commutator = (1, 2, -1, -2)
    assert subgroup_return(commutator, 'free-commutator')
    assert not subgroup_return((1,)+commutator+(-1,), 'free-commutator')
    compose = lambda a, b: tuple(a[b[i]] for i in range(4))
    identity = tuple(range(4))
    group, pending = {identity}, [identity]
    while pending:
        element = pending.pop()
        for generator in (FIRST, SECOND):
            new = compose(generator, element)
            if new not in group:
                group.add(new)
                pending.append(new)
    assert len(group) == 24 and sum(p[0] == 0 for p in group) == 6
    permutation = identity
    for letter in commutator:
        permutation = compose(permutation, PERMUTATIONS[letter])
    assert permutation == (0, 2, 3, 1) != identity
    for x, y in product(range(3), repeat=2):
        assert subgroup_return(tuple(g for g in (x, y, -x, -y) if g), 'four-state')
    return count


def verify(data):
    expected = {(family, length) for family in FAMILIES for length in (1, 2, 3)}
    rank_count = tested_masks = 0
    for record in data['records']:
        family, length = record['family'], record['length']
        expected.remove((family, length))
        cuts, support = coefficient_rows(length, family)
        assert support == record['support']
        assert binary_rank(cuts[1][0]) == 1
        ranks = rank_pairs(cuts, low=True)
        assert ranks == list(map(tuple, record['ranks']))
        threshold = record['threshold']
        assert threshold == THRESHOLDS[family][length-1] >= 24**length
        detector = record['detector']
        assert detector.bit_count() == 1
        assert ((len(ranks)-1) & detector).bit_count() % 2 == 1
        assert min(r*c for mask, (r, c) in enumerate(ranks)
                   if (mask & detector).bit_count() % 2) == threshold
        endpoint = 0
        for mask in record['upper_path']:
            endpoint ^= mask
            r, c = ranks[mask]
            assert r*c <= threshold
        assert endpoint == len(ranks)-1
        if length == 2:
            # Swapping the two physical positions changes this entry from
            # zero to t^4+t^6, despite retaining identical local polynomials.
            first = sum(((side[14] >> 46) & 1) << k for k, side in enumerate(cuts[0]))
            second = sum(((side[46] >> 14) & 1) << k for k, side in enumerate(cuts[0]))
            assert first == 0 and second == 80
        rank_count += 2*len(ranks)
        tested_masks += len(ranks)
    assert not expected
    assert 24**7 > 3**20 and 2*5**2 > 7**2
    for name, digest in data['source_sha256'].items():
        assert sha256((ROOT/'tools'/name).read_bytes()).hexdigest() == digest
    return dict(complete_finite_cases=6, coefficient_masks=tested_masks,
                independently_replayed_cut_ranks=rank_count,
                independent_language_words=language_controls(),
                exact_finite_rho_floor='5/7 > 1/sqrt(2)',
                scope=data['scope'], factoring_exponent='1/2; unchanged')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    parser.add_argument('--evidence', type=Path, default=ROOT/'evidence/subgroup-return-crossings.json')
    args = parser.parse_args()
    if args.generate:
        data = generate()
        args.evidence.write_text(json.dumps(data, separators=(',', ':'))+'\n')
    else:
        data = json.loads(args.evidence.read_text())
    print(json.dumps(verify(data)))


if __name__ == '__main__':
    main()
