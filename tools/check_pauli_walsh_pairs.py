#!/usr/bin/env python3
"""Exact S-certificate for two-type Pauli combinations in eight fixed bases.

Includes all coefficient ratios over characteristic-three extension fields,
both Fourier orientations, and single atoms. Mixed-orientation pairs have
a separate rank-difference exclusion proved in the companion note.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from fractions import Fraction
import hashlib
import json
from pathlib import Path
from time import monotonic

from check_pauli_walsh_dictionary import walsh

BASES = ((1,2,4,8,16,32), (9,22,46,29,41,4), (53,22,62,58,32,31),
         (6,62,33,11,15,38), (18,47,48,51,7,35), (44,60,47,33,48,41),
         (55,45,38,2,18,59), (9,26,11,44,25,40))


def add3(a,b):
    a1,a2=a; b1,b2=b
    az,bz=~(a1|a2),~(b1|b2)
    return ((a1&bz)|(b1&az)|(a2&b2), (a2&bz)|(b2&az)|(a1&b1))


def sub3(a,b):
    return add3(a,(b[1],b[0]))


def arithmetic_controls():
    encode = lambda a: (int(a==1),int(a==2))
    for a in range(3):
        for b in range(3):
            assert add3(encode(a),encode(b))==encode((a+b)%3)
            assert sub3(encode(a),encode(b))==encode((a-b)%3)


def inverse2(rows):
    m=len(rows)
    a=[row|(1<<(m+i)) for i,row in enumerate(rows)]
    for col in range(m):
        pivot=next(i for i in range(col,m) if (a[i]>>col)&1)
        a[col],a[pivot]=a[pivot],a[col]
        for i in range(m):
            if i!=col and ((a[i]>>col)&1):a[i]^=a[col]
    assert [row&((1<<m)-1) for row in a]==[1<<i for i in range(m)]
    return [row>>m for row in a]


def apply2(rows,x):
    return sum(((row&x).bit_count()&1)<<i for i,row in enumerate(rows))


def atoms():
    m,d=6,64
    output=[]
    for basis,rows in enumerate(BASES):
        inv=inverse2(rows)
        invt=[sum(((inv[j]>>i)&1)<<j for j in range(m)) for i in range(m)]
        xmap=[apply2(rows,x) for x in range(d)]
        zmap=[apply2(invt,z) for z in range(d)]
        masks=defaultdict(int)
        for x in range(d):
            for z in range(d):
                a,b=xmap[x],zmap[z]
                assert ((a&b).bit_count()-(x&z).bit_count())%2==0
                both=(a&b).bit_count();first=(a&~b).bit_count();second=(b&~a).bit_count()
                kind=(m-both-first-second,first,second,both)
                masks[kind]|=1<<(x*d+z)
        assert len(masks)==84
        for kind,mask in sorted(masks.items()):
            spectrum=walsh([(mask>>i)&1 for i in range(d*d)])
            first=second=0
            for i,value in enumerate(spectrum):
                if value%3==1:first|=1<<i
                elif value%3==2:second|=1<<i
            r,c=(first|second).bit_count(),mask.bit_count()
            assert r>=720 and c<=180 and r*c>=d*d
            output.append(({'basis':basis,'type':kind},(mask,0),(first,second)))
    assert len(output)==672
    return output


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path)
    args=parser.parse_args();start=monotonic()
    arithmetic_controls();data=atoms();d=64
    profiles=Counter();witnesses={};nonzero=0;zero=0
    for i,(mi,gi,hi) in enumerate(data):
        for j in range(i):
            mj,gj,hj=data[j]
            for coefficient,op in ((1,add3),(2,sub3),('outside_F3',None)):
                if op is None:
                    # A+lambda B has no extra zero when lambda is outside F3.
                    g=(gi[0]|gi[1]|gj[0]|gj[1],0)
                    h=(hi[0]|hi[1]|hj[0]|hj[1],0)
                else:g,h=op(gi,gj),op(hi,hj)
                c=(g[0]|g[1]).bit_count();r=(h[0]|h[1]).bit_count()
                if not c:
                    assert not r;zero+=1;continue
                nonzero+=1
                assert r*c>=d*d
                if r*c>=295**2:continue
                profiles[r,c]+=1
                witnesses.setdefault((r,c),{'first':mi,'second':mj,'ratio':coefficient})
    assert nonzero+zero==3*len(data)*(len(data)-1)//2
    # Single-atom cases not generated by a pair of distinct dictionary entries.
    singles=((4096,1),(2688,6),(2688,15),(2048,20),(2892,30))
    retained=set(profiles)|set(singles)
    u,v=Fraction(7,500),Fraction(17,4)
    for r,c in retained:
        linear=u*(r+c)+v*min(r,c)
        assert linear>=0 and linear*linear<=r*c
    assert 577*577-2*408*408==1
    assert 359**408>d**577
    # Every nonzero Pauli tensor costs at least d. With two or more pieces,
    # total S<d^sqrt2<359 forces every individual cost below 359-d=295.
    assert 359-d==295
    # A mixed orientation has each cut rank at least720-180=540.
    assert 720-180==540 and 540>359
    lower=2*d*d*u+d*v
    assert lower==Fraction(48336,125)
    assert lower.numerator**408>d**577*lower.denominator**408
    here=Path(__file__)
    result={'status':'PASS','scope':'Finite eight-basis two-type Pauli dictionary; no asymptotic claim.',
            'field_characteristic':3,'extension_ratios_included':True,'fourier_duals_included':True,
            'basis_matrices':BASES,'raw_atoms':len(data),'nonzero_pair_cases':nonzero,'zero_pair_cases':zero,
            'retained_rank_profiles':len(retained),
            'dual':{'ordinary_rank_weight':'7/500','minimum_cut_weight':'17/4',
                    'rank_sum_lower_bound':'48336/125','strictly_above_target':True},
            'threshold':{'target_upper':359,'minimum_nonzero_piece_cost':64,'individual_cost_upper':295,
                         'mixed_orientation_rank_lower':540},
            'profiles':[{'row':r,'column':c,'count':profiles[r,c],
                         'witness':witnesses.get((r,c),'single atom')} for r,c in sorted(retained)],
            'source_sha256':{here.name:hashlib.sha256(here.read_bytes()).hexdigest(),
                             'check_pauli_walsh_dictionary.py':hashlib.sha256(here.with_name('check_pauli_walsh_dictionary.py').read_bytes()).hexdigest()},
            'seconds':monotonic()-start}
    if args.output:args.output.write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({k:v for k,v in result.items() if k!='profiles'},indent=2))


if __name__=='__main__':main()
