"""Path B, checker 1: genus obstruction is invariant under smooth multipliers.

Lemma B1 (see note.md): N = q1*q2, (q1/q2) = (q2/q1) = -1; s coprime to N with
D = -s*N a discriminant; every prime factor of s and every generator norm a
quadratic residue mod q1 and mod q2.  Then no element of order <= 2 of the
subgroup H generated by those prime forms splits N.

This script verifies, with exact arithmetic, on explicit examples:
  (1) the divisor-based enumeration of ambiguous reduced forms agrees with
      brute-force enumeration for small discriminants;
  (2) chi_q is multiplicative on random products (sanity of the genus map);
  (3) for "joint-residue" pairs (all primes <= Y are QR mod q1 and q2) and
      every admissible Y-smooth multiplier s <= SMAX: every base prime form
      has chi_{q1} = chi_{q2} = +1, every ambiguous form splitting N has a
      -1 character, and an explicit BFS closure of H contains no ambiguous
      form splitting N (while such forms exist in the full class group);
  (4) a control pair (some p <= Y is a nonresidue) where H does contain a
      splitting ambiguous form.
Run:  python3 check_genus_invariance.py
"""
import random
import sys
from math import gcd, isqrt
import bqf

random.seed(20261101)


def divisors_from_factors(fac):
    ds = [1]
    for p, e in fac.items():
        ds = [d * p**k for d in ds for k in range(e + 1)]
    return sorted(ds)


def factor_small(n, primes):
    fac = {}
    for p in primes:
        while n % p == 0:
            fac[p] = fac.get(p, 0) + 1
            n //= p
    return fac, n


def ambiguous_forms(D, divs):
    absD = -D
    out = set()
    if D % 4 == 0:
        for a in divs:
            if (absD // 4) % a == 0 if absD % 4 == 0 else False:
                c = absD // 4 // a
                if a <= c and gcd(a, c) == 1:
                    out.add((a, 0, c))
    for a in divs:
        if a * a * 3 > absD:
            continue
        num = a * a + absD
        if num % (4 * a) == 0:
            c = num // (4 * a)
            if c >= a and gcd(a, c) == 1:
                out.add(bqf.reduce_form((a, a, c)) if c == a else (a, a, c))
    for m in divs:
        mp = absD // m
        if m >= mp:
            continue
        if (mp - m) % 2 or (m + mp) % 4:
            continue
        b = (mp - m) // 2
        a = (m + mp) // 4
        if 0 < b < a and gcd(a, b) == 1:
            out.add((a, b, a))
    for f in out:
        assert bqf.disc(f) == D and bqf.is_reduced(f), f
    return out


def check_enumeration():
    count = 0
    for absD in range(3, 4000):
        D = -absD
        if D % 4 not in (0, 1):
            continue
        brute = {f for f in bqf.reduced_forms(D) if bqf.is_ambiguous_reduced(f)}
        fac, rest = factor_small(absD, bqf.primes_upto(absD))
        assert rest == 1
        fast = ambiguous_forms(D, divisors_from_factors(fac))
        assert brute == fast, (D, brute, fast)
        # every reduced ambiguous form is of order <= 2
        for f in brute:
            assert bqf.compose(f, f) == bqf.identity(D)
        count += 1
    return count


def joint_residue_primes(Y, lo, hi, count):
    ps = [p for p in bqf.primes_upto(Y)]
    out = []
    q = lo + (1 - lo) % 8  # q = 1 mod 8 makes 2 a QR and (q1/q2) symmetric
    while q < hi and len(out) < count:
        if bqf.is_prime(q) and all(bqf.legendre(p, q) == 1 for p in ps):
            out.append(q)
        q += 8
    return out


def closure(gens, D):
    e = bqf.identity(D)
    seen = {e}
    frontier = [e]
    while frontier:
        nxt = []
        for f in frontier:
            for g in gens:
                h = bqf.compose(f, g)
                if h not in seen:
                    seen.add(h)
                    nxt.append(h)
        frontier = nxt
    return seen


def run_case(q1, q2, Y, s, do_bfs=True, label=""):
    N = q1 * q2
    D = -s * N
    assert D % 4 in (0, 1) and gcd(s, N) == 1
    primesY = bqf.primes_upto(Y)
    base = []
    for p in primesY:
        if N % p == 0:
            continue
        f = bqf.prime_form(D, p)
        if f is not None:
            base.append((p, f))
    chars_base = [(p, bqf.genus_char(f, q1), bqf.genus_char(f, q2)) for p, f in base]
    fac_s, rest = factor_small(s, primesY)
    assert rest == 1
    fac = dict(fac_s)
    fac[q1] = fac.get(q1, 0) + 1
    fac[q2] = fac.get(q2, 0) + 1
    amb = ambiguous_forms(D, divisors_from_factors(fac))
    splitting = []
    for f in amb:
        m = bqf.ambiguous_leading(f)
        g = gcd(m, N)
        if 1 < g < N:
            splitting.append((f, g, bqf.genus_char(f, q1), bqf.genus_char(f, q2)))
    res = {
        "label": label, "q1": q1, "q2": q2, "s": s, "D": D, "Y": Y,
        "base_size": len(base),
        "base_all_plus": all(c1 == 1 and c2 == 1 for _, c1, c2 in chars_base),
        "num_ambiguous": len(amb),
        "num_splitting_ambiguous": len(splitting),
        "splitting_all_have_minus": all(c1 == -1 or c2 == -1 for _, _, c1, c2 in splitting),
    }
    if do_bfs:
        H = closure([f for _, f in base] + [bqf.inverse(f) for _, f in base], D)
        # multiplicativity sanity on H
        Hl = list(H)
        for _ in range(200):
            f, g = random.choice(Hl), random.choice(Hl)
            fg = bqf.compose(f, g)
            for q in (q1, q2):
                assert bqf.genus_char(fg, q) == bqf.genus_char(f, q) * bqf.genus_char(g, q)
        res["H_size"] = len(H)
        res["H_splitting_ambiguous"] = sum(1 for f, _, _, _ in splitting if f in H)
        res["H_ambiguous"] = sum(1 for f in amb if f in H)
    return res


def main():
    n_enum = check_enumeration()
    print(f"[1] divisor enumeration of ambiguous reduced forms == brute force for {n_enum} discriminants |D|<4000: OK")

    # [2] multiplicativity of genus characters on random forms
    for D, qs in [(-3 * 5 * 7 * 11 * 13 * 4, (3, 5, 7, 11, 13)), (-7 * 11 * 19 * 23 * 4, (7, 11, 19, 23)), (-7 * 11 * 19, (7, 11, 19))]:
        F = bqf.reduced_forms(D)
        for _ in range(2000):
            f, g = random.choice(F), random.choice(F)
            fg = bqf.compose(f, g)
            for q in qs:
                assert bqf.genus_char(fg, q) == bqf.genus_char(f, q) * bqf.genus_char(g, q)
    print("[2] chi_q(fg) = chi_q(f) chi_q(g) on 4000 random products: OK")

    ok = True
    for Y, lo, hi in [(13, 1, 10**6), (23, 1, 10**7), (31, 1, 10**8)]:
        qs = joint_residue_primes(Y, lo, hi, 60)
        pair = None
        for i in range(len(qs)):
            for j in range(i + 1, len(qs)):
                if bqf.legendre(qs[i], qs[j]) == -1:
                    pair = (qs[i], qs[j])
                    break
            if pair:
                break
        assert pair, Y
        q1, q2 = pair
        N = q1 * q2
        mults = [s for s in range(1, 200) if (-s * N) % 4 in (0, 1)
                 and factor_small(s, bqf.primes_upto(Y))[1] == 1 and gcd(s, N) == 1]
        bfs_mults = {s for s in mults if s in (3, 4, 7, 8)}  # LP multiplier list for N = 1 mod 4
        print(f"[3] Y={Y}: joint-residue pair q1={q1}, q2={q2}, (q1/q2)={bqf.legendre(q1, q2)}, "
              f"least nonresidues n(q1)={least_nr(q1)}, n(q2)={least_nr(q2)}; {len(mults)} multipliers s<200")
        for s in mults:
            do_bfs = s in bfs_mults and s * N < 2 * 10**11
            r = run_case(q1, q2, Y, s, do_bfs=do_bfs)
            good = r["base_all_plus"] and r["splitting_all_have_minus"] and r["num_splitting_ambiguous"] > 0
            if do_bfs:
                good = good and r["H_splitting_ambiguous"] == 0
                print(f"    s={s:3d} D={r['D']} |base|={r['base_size']} |H|={r['H_size']} "
                      f"ambiguous={r['num_ambiguous']} splitting={r['num_splitting_ambiguous']} "
                      f"ambiguous_in_H={r['H_ambiguous']} splitting_in_H={r['H_splitting_ambiguous']}")
            ok &= good
        print(f"    all {len(mults)} multipliers: base chars all +1, every splitting ambiguous form has a -1 char: {ok}")

    # [4] control: the same joint-residue N, but a larger base that contains a
    # prime which is a nonresidue mod q1 and q2 (17 for this pair): coverage returns.
    Y = 13
    qs = joint_residue_primes(Y, 1, 10**6, 60)
    q1, q2 = next((a, b) for i, a in enumerate(qs) for b in qs[i + 1:] if bqf.legendre(a, b) == -1)
    for Yc in (13, 16, 17, 60):
        r = run_case(q1, q2, Yc, 3, do_bfs=True, label="control")
        print(f"[4] control N={q1}*{q2}, s=3, base primes <= {Yc}: |base|={r['base_size']} |H|={r['H_size']}, "
              f"splitting ambiguous in H = {r['H_splitting_ambiguous']} of {r['num_splitting_ambiguous']}")
    ok &= r["H_splitting_ambiguous"] > 0
    print("RESULT:", "PASS" if ok else "FAIL")
    sys.exit(0 if ok else 1)


def least_nr(q):
    n = 2
    while bqf.legendre(n, q) != -1:
        n += 1
    return n


if __name__ == "__main__":
    main()
