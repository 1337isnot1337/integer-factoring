#!/usr/bin/env python3
"""Mixed-pair rank profiles across outside targets on a 40-bit cycle.

Reuses the exact cycle from tools/check_mixed_pair_gap_cycle.py and sweeps
every split prime in (177, max_target] that lies in the order-198850 cycle
generated by 5.  For each target it builds the same pair rows at exponents
1..max_window, records the rank profile, the first full window, the
selected maximal minor, the HNF row-lattice index, and the two-part
extraction.

The point is finite scope, not a uniform theorem: pair rows alone need not
cover every target at window 3, and in this cycle every rank failure is in
the small-index density-covered regime.  See
research/mixed-pair-rank-sweep.md.
"""
import argparse
import json
from math import gcd, isqrt

from arithmetic_two_group import power, project_to_two_part, two_group_basis
from binary_quadratic_forms import ambiguous_factor, inverse_form, reduce_form
from dynamic_leading_norm_relations import leading_norm_word
from leading_power_smooth_relations import compose_with_prime_form
from prime_form_factor_base import build_prime_form_factor_base, primes_through
from quadratic_ideal_hnf import compose_forms_hnf

from check_mixed_pair_gap_cycle import (
    BASE_PRIME, CUTOFF, INTEGER, cycle_forms, determinant,
    echelon_pivot_rows, replay, row_hnf_basis, split_factorization,
)


def probe(max_target, max_window, explicit_targets=None):
    delta = -INTEGER
    base = build_prime_form_factor_base(delta, CUTOFF)
    records = {record.prime: (record.root, tuple(record.positive))
               for record in base['records']}
    base_primes = tuple(sorted(records))
    assert len(base_primes) == 22
    forms, index, identity = cycle_forms(records)
    period = len(forms)
    assert period == 198850
    logs = {prime: index[reduce_form(records[prime][1])]
            for prime in base_primes}
    assert logs[BASE_PRIME] == 1

    larger = build_prime_form_factor_base(delta, max_target)
    larger_records = {record.prime: (record.root, tuple(record.positive))
                      for record in larger['records']}
    height = isqrt(INTEGER//3)
    fourth_root = abs(delta)**0.25
    if explicit_targets is None:
        outside = [prime for prime in primes_through(max_target)
                   if prime > CUTOFF and prime in larger_records]
    else:
        outside = sorted(set(explicit_targets))
        for target in outside:
            assert target <= max_target, (target, max_target)
            assert target in larger_records, target
    results = []
    skipped = []
    for target in outside:
        records_all = dict(records)
        records_all[target] = larger_records[target]
        target_form = reduce_form(records_all[target][1])
        if target_form not in index:
            skipped.append({'target': target, 'reason': 'not-in-cycle'})
            continue
        targets = tuple(sorted(base_primes + (target,)))
        positions = {prime: pos for pos, prime in enumerate(targets)}
        width = len(targets)
        target_logs = dict(logs)
        target_logs[target] = index[target_form]
        order = period//gcd(period, target_logs[target])
        target_index = gcd(period, target_logs[target])

        rows_by_window = {}
        target_pair_hits = 0
        for left_index, left in enumerate(targets):
            for right in targets[left_index:]:
                for exponent in range(1, max_window+1):
                    form = forms[(exponent*(target_logs[left]+target_logs[right]))
                                 % period]
                    leading = form[0]
                    if leading == 1:
                        continue
                    parts = split_factorization(leading, records)
                    if parts is None:
                        continue
                    terms, new = leading_norm_word(
                        INTEGER, form, parts, records_all)
                    assert not new
                    row = [0]*width
                    row[positions[left]] += exponent
                    row[positions[right]] += exponent
                    for prime, value in terms.items():
                        row[positions[prime]] -= value
                    if any(row) and row not in rows_by_window.setdefault(
                            exponent, []):
                        rows_by_window[exponent].append(row)
                        if left == target or right == target:
                            target_pair_hits += 1

        pooled = []
        profile = []
        full_window = None
        selected = None
        for window in range(1, max_window+1):
            pooled.extend(rows_by_window.get(window, []))
            rank, current_pivots = echelon_pivot_rows(pooled)
            profile.append({'window': window, 'rows': len(pooled),
                            'rank': rank})
            if full_window is None and rank == width:
                full_window = window
                selected = [pooled[i] for i in current_pivots[:width]]

        record = {
            'target': target,
            'order': order,
            'index': target_index,
            'index_above_fourth_root': target_index > fourth_root,
            'first_full_window': full_window,
            'rank_profile': profile,
            'rows_by_window': {str(window): len(rows)
                               for window, rows in rows_by_window.items()},
            'target_pair_hits': target_pair_hits,
            'target_isolated': target_pair_hits == 0,
        }
        if selected is not None:
            for row in selected:
                assert replay(row, targets, records_all, identity) == identity
            minor_determinant = int(determinant(selected))
            assert minor_determinant % period == 0
            generators = [records_all[prime][1] for prime in targets]
            projected = project_to_two_part(
                generators, abs(minor_determinant), identity,
                compose_forms_hnf)
            basis = two_group_basis(
                projected, identity, compose_forms_hnf, inverse_form,
                period.bit_length())
            tops = [power(form, 1 << (power_order-1), identity,
                          compose_forms_hnf)
                    for form, power_order in basis]
            factors = [ambiguous_factor(form, INTEGER) for form in tops]
            factor = next((value for value in factors if value), None)
            assert factor in (1000003, 1000033)
            record['selected_minor_determinant'] = minor_determinant
            record['minor_multiple'] = minor_determinant//period
            record['extracted_factor'] = factor

            hnf_basis, hnf_rank = row_hnf_basis(pooled, width)
            assert hnf_rank == width
            for row in hnf_basis:
                assert replay(row, targets, records_all, identity) == identity
            lattice_index = abs(int(determinant(hnf_basis)))
            assert lattice_index % period == 0
            record['lattice_index'] = lattice_index
            record['lattice_multiple'] = lattice_index//period
            record['lattice_bit_length'] = lattice_index.bit_length()
            lattice_projected = project_to_two_part(
                generators, lattice_index, identity, compose_forms_hnf)
            lattice_basis = two_group_basis(
                lattice_projected, identity, compose_forms_hnf, inverse_form,
                period.bit_length())
            lattice_tops = [
                power(form, 1 << (power_order-1), identity,
                      compose_forms_hnf)
                for form, power_order in lattice_basis]
            lattice_factors = [
                ambiguous_factor(form, INTEGER) for form in lattice_tops]
            lattice_factor = next(
                (value for value in lattice_factors if value), None)
            assert lattice_factor in (1000003, 1000033)
            record['lattice_extracted_factor'] = lattice_factor
        results.append(record)

    return {
        'integer': INTEGER,
        'factorization': [1000003, 1000033],
        'discriminant': delta,
        'cutoff': CUTOFF,
        'max_target': max_target,
        'height_bound': height,
        'fourth_root': fourth_root,
        'cycle_order': period,
        'base_primes': list(base_primes),
        'outside_targets_in_cycle': [record['target'] for record in results],
        'outside_targets_skipped': skipped,
        'target_selection': ('explicit' if explicit_targets is not None
                             else 'all-split-primes'),
        'results': results,
        'scope': ('Finite rank and lattice-index diagnostic over outside '
                  'split primes in the 40-bit order-198850 cycle. Pair rows '
                  'at windows 1..max_window are tested for full rank, HNF '
                  'row-lattice index, and extraction. No uniform pair supply, '
                  'rank-window, lattice-index, or complete-bound claim.'),
    }


def summary(receipt):
    full_windows = {}
    for record in receipt['results']:
        key = record['first_full_window']
        full_windows[str(key)] = full_windows.get(str(key), 0) + 1
    failures = [record for record in receipt['results']
                if record['first_full_window'] is None]
    gap_results = [record for record in receipt['results']
                   if record['index_above_fourth_root']]
    return {
        'outside_targets_in_cycle': len(receipt['outside_targets_in_cycle']),
        'outside_targets_skipped': len(receipt['outside_targets_skipped']),
        'full_windows': full_windows,
        'rank_failures': [{
            'target': record['target'],
            'order': record['order'],
            'index': record['index'],
            'rank_profile': record['rank_profile'],
            'target_pair_hits': record['target_pair_hits'],
            'target_isolated': record['target_isolated'],
        } for record in failures],
        'isolated_targets': [
            record['target'] for record in receipt['results']
            if record['target_isolated']],
        'index_above_fourth_root': len(gap_results),
        'gap_results': [{
            'target': record['target'],
            'order': record['order'],
            'index': record['index'],
            'first_full_window': record['first_full_window'],
            'minor_multiple': record.get('minor_multiple'),
            'lattice_multiple': record.get('lattice_multiple'),
            'extracted_factor': record.get('extracted_factor'),
            'lattice_extracted_factor': record.get('lattice_extracted_factor'),
            'target_pair_hits': record['target_pair_hits'],
        } for record in gap_results],
        'extraction_successes': sum(
            1 for record in receipt['results']
            if record.get('extracted_factor') in (1000003, 1000033)),
        'lattice_extraction_successes': sum(
            1 for record in receipt['results']
            if record.get('lattice_extracted_factor') in (1000003, 1000033)),
        'lattice_multiples': {
            str(key): sum(1 for record in receipt['results']
                          if record.get('lattice_multiple') == key)
            for key in sorted({record.get('lattice_multiple')
                               for record in receipt['results']
                               if record.get('lattice_multiple') is not None})},
        'max_lattice_multiple': max(
            (record['lattice_multiple'] for record in receipt['results']
             if record.get('lattice_multiple') is not None), default=None),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--max-target', type=int, default=None)
    parser.add_argument('--max-window', type=int, default=3)
    parser.add_argument('--targets', help='comma-separated target subset')
    parser.add_argument('--output')
    arguments = parser.parse_args()
    explicit = None
    if arguments.targets:
        explicit = [int(value) for value in arguments.targets.split(',')
                    if value.strip()]
    if arguments.max_target is None:
        arguments.max_target = max(explicit) if explicit else 2500
    receipt = probe(arguments.max_target, arguments.max_window,
                    explicit_targets=explicit)
    text = json.dumps(receipt, indent=2, sort_keys=True) + '\n'
    if arguments.output:
        with open(arguments.output, 'w') as handle:
            handle.write(text)
    print(json.dumps(summary(receipt), indent=2, sort_keys=True))


if __name__ == '__main__':
    main()
