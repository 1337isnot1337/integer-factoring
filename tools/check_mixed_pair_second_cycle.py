#!/usr/bin/env python3
"""Probe half-cycle repair on a second cycle with higher 2-adic order.

The main mixed-pair cycle has N=1000036000099, period 198850=2*99425, so the
half-cycle construction only needs the first 2-primary layer.  This control
uses N=450296711=20323*22157, base generator 2, and the order-20456 cycle
generated by 2.  Since 20456=8*2557, the period has v_2=3.  A cutoff-60 base
gives nine split base primes and full pair-row rank at window 4; split targets
through 20000 are scanned.

The direct generalisation of the half-order difference row,
``(ord_p/2)e_p - (h/2)e_anchor`` for even order and ``ord_p e_p`` for odd
order, leaves every residual index at two.  This is the level-one
specialization; the proved two-primary saturation theorem predicts the
top-level, unit-aligned pair row for these order-``h`` targets.  Deeper
layered differences ``(h/2^e)(e_p-e_q)`` for logs congruent modulo ``2^e``
are tested.  Layers one and two also leave index two; the primitive
layer-three difference ``(h/8)(e_p-e_q)`` is an odd multiple of the
unit-aligned theorem row and repairs each residual to index one.  All rows
replay and the repaired covolume annihilators extract a factor.  Finite
second-cycle check of the ``v_2(h)=3`` top-level branch; the theorem supplies
the general depth/pair selection.  Cost and complete-bound claims remain
open.
"""
import argparse
import json
from math import gcd

from arithmetic_two_group import power, project_to_two_part, two_group_basis
from binary_quadratic_forms import ambiguous_factor, inverse_form, reduce_form
from check_mixed_pair_gap_cycle import determinant, replay, row_hnf_basis
from dynamic_leading_norm_relations import leading_norm_word
from leading_power_smooth_relations import compose_forms_hnf, compose_with_prime_form
from prime_form_factor_base import build_prime_form_factor_base, primes_through


INTEGER = 450296711
FACTORIZATION = (20323, 22157)
CUTOFF = 60
BASE_PRIME = 2
WINDOW = 4
TARGET_LIMIT = 20000
EXPECTED_PERIOD = 20456
EXPECTED_BASE_PRIMES = (2, 3, 5, 11, 23, 29, 31, 41, 59)
EXPECTED_RESIDUAL = (79, 653, 3911, 17321)


def cycle_forms(delta, records, base_prime):
    identity = (1, 1, (1-delta)//4)
    current = identity
    forms = []
    index = {}
    while True:
        index[current] = len(forms)
        forms.append(current)
        current = compose_with_prime_form(
            current, base_prime, *records[base_prime])
        if current == identity:
            return forms, index, identity


def split_factorization(value, records, primes):
    parts = []
    for prime in primes:
        if value % prime:
            continue
        exponent = 0
        while value % prime == 0:
            value //= prime
            exponent += 1
        if prime not in records:
            return None
        parts.append((prime, exponent))
        if value == 1:
            break
    return tuple(parts) if value == 1 else None


def build_rows(integer, records, forms, index, period, records_all, logs,
               targets, primes):
    positions = {prime: position for position, prime in enumerate(targets)}
    target_logs = dict(logs)
    rows = []
    seen = set()
    for left_position, left in enumerate(targets):
        for right in targets[left_position:]:
            for exponent in range(1, WINDOW+1):
                form = forms[
                    (exponent*(target_logs[left] + target_logs[right]))
                    % period]
                if form[0] == 1:
                    continue
                parts = split_factorization(form[0], records, primes)
                if parts is None:
                    continue
                terms, new = leading_norm_word(
                    integer, form, parts, records_all)
                assert not new
                row = [0]*len(targets)
                row[positions[left]] += exponent
                row[positions[right]] += exponent
                for prime, value in terms.items():
                    row[positions[prime]] -= value
                key = tuple(row)
                if any(row) and key not in seen:
                    seen.add(key)
                    rows.append(row)
    return rows


def lattice_index(rows, width, period):
    basis, rank = row_hnf_basis(rows, width)
    if rank != width:
        return None
    covolume = abs(int(determinant(basis)))
    assert covolume % period == 0
    return covolume//period


def layered_rows(targets, logs, period, exponent):
    width = len(targets)
    modulus = 1 << exponent
    assert period % modulus == 0
    coefficient = period//modulus
    groups = {}
    for position, target in enumerate(targets):
        groups.setdefault(logs[target] % modulus, []).append(position)
    rows = []
    for residue, positions in groups.items():
        if residue == 0:
            for position in positions:
                row = [0]*width
                row[position] = coefficient
                rows.append(('single', targets[position], None, row))
        else:
            for position in positions[1:]:
                row = [0]*width
                row[positions[0]] = coefficient
                row[position] = -coefficient
                rows.append((
                    'difference', targets[positions[0]],
                    targets[position], row))
    return rows


def half_order_rows(targets, logs, period, anchor):
    width = len(targets)
    anchor_position = targets.index(anchor)
    rows = []
    for position, target in enumerate(targets):
        order = period//gcd(period, logs[target])
        row = [0]*width
        if order % 2 == 0:
            if order == period and position == anchor_position:
                continue
            row[position] += order//2
            row[anchor_position] -= period//2
        else:
            row[position] = order
        if any(row):
            rows.append(row)
    return rows


def extract(records_all, targets, basis, index_value, period, identity):
    generators = [records_all[target][1] for target in targets]
    projected = project_to_two_part(
        generators, index_value, identity, compose_forms_hnf)
    basis_two = two_group_basis(
        projected, identity, compose_forms_hnf, inverse_form,
        period.bit_length())
    tops = [
        power(form, 1 << (power_order-1), identity, compose_forms_hnf)
        for form, power_order in basis_two]
    factors = [ambiguous_factor(form, INTEGER) for form in tops]
    return next(
        (factor for factor in factors if factor in FACTORIZATION), None)


def run():
    delta = -INTEGER
    base = build_prime_form_factor_base(delta, CUTOFF)
    records = {
        record.prime: (record.root, tuple(record.positive))
        for record in base['records']}
    base_primes = tuple(sorted(records))
    assert base_primes == EXPECTED_BASE_PRIMES
    primes = tuple(primes_through(CUTOFF))
    forms, index, identity = cycle_forms(delta, records, BASE_PRIME)
    period = len(forms)
    assert period == EXPECTED_PERIOD
    v2_period = (period & -period).bit_length()-1
    assert v2_period == 3
    logs = {
        prime: index[reduce_form(records[prime][1])]
        for prime in base_primes}
    assert logs[base_primes[0]] == 1
    anchor = base_primes[0]

    extension = build_prime_form_factor_base(delta, TARGET_LIMIT)
    extension_records = {
        record.prime: (record.root, tuple(record.positive))
        for record in extension['records']}

    counts = {}
    failures = []
    residual = []
    for target in primes_through(TARGET_LIMIT):
        if target <= CUTOFF or target not in extension_records:
            continue
        target_form = reduce_form(extension_records[target][1])
        if target_form not in index:
            continue
        targets = tuple(sorted(base_primes + (target,)))
        target_logs = dict(logs)
        target_logs[target] = index[target_form]
        records_all = dict(records)
        records_all[target] = extension_records[target]
        rows = build_rows(
            INTEGER, records, forms, index, period, records_all,
            target_logs, targets, primes)
        current = lattice_index(rows, len(targets), period)
        if current is None:
            failures.append(target)
            continue
        counts[current] = counts.get(current, 0) + 1
        if current <= 1:
            continue

        half_rows = half_order_rows(targets, target_logs, period, anchor)
        for row in half_rows:
            assert replay(row, targets, records_all, identity) == identity
        half_index = lattice_index(rows + half_rows, len(targets), period)

        layer_indexes = {}
        base_rows = list(rows)
        for exponent in range(1, v2_period+1):
            candidate_rows = layered_rows(
                targets, target_logs, period, exponent)
            for _, _, _, row in candidate_rows:
                assert replay(row, targets, records_all, identity) == identity
            base_rows += [row for _, _, _, row in candidate_rows]
            layer_indexes[str(exponent)] = lattice_index(
                base_rows, len(targets), period)

        primitive = None
        primitive_index = None
        for kind, left, right, row in layered_rows(
                targets, target_logs, period, v2_period):
            candidate_index = lattice_index(rows + [row], len(targets), period)
            if candidate_index == 1:
                primitive = {
                    'kind': kind,
                    'pair': [left, right] if right is not None else [left],
                    'coefficients': [period//(1 << v2_period),
                                     -period//(1 << v2_period)]
                    if right is not None else [period//(1 << v2_period)],
                }
                primitive_index = candidate_index
                break
        assert primitive is not None
        assert primitive_index == 1

        repaired_rows = rows + [row for kind, left, right, row in layered_rows(
            targets, target_logs, period, v2_period) if (
                (kind == primitive['kind'] and
                 left == primitive['pair'][0] and
                 (right == primitive['pair'][1]
                  if len(primitive['pair']) == 2 else right is None)))]
        repaired_basis, repaired_rank = row_hnf_basis(
            repaired_rows, len(targets))
        assert repaired_rank == len(targets)
        for row in repaired_basis:
            assert replay(row, targets, records_all, identity) == identity
        repaired_covolume = abs(int(determinant(repaired_basis)))
        assert repaired_covolume == period

        factor = extract(
            records_all, targets, repaired_basis, repaired_covolume,
            period, identity)
        assert factor in FACTORIZATION

        residual.append({
            'target': target,
            'log': target_logs[target],
            'target_order': period//gcd(period, target_logs[target]),
            'base_lattice_index': current,
            'half_order_lattice_index': half_index,
            'layered_lattice_indexes': layer_indexes,
            'primitive_row': primitive,
            'repaired_lattice_index': primitive_index,
            'repaired_covolume': repaired_covolume,
            'extracted_factor': factor,
        })

    assert not failures
    assert sum(counts.values()) == 1131
    assert counts == {1: 1127, 2: 4}
    assert [record['target'] for record in residual] == list(EXPECTED_RESIDUAL)
    assert all(record['base_lattice_index'] == 2 for record in residual)
    assert all(record['half_order_lattice_index'] == 2 for record in residual)
    assert all(record['layered_lattice_indexes'] == {
        '1': 2, '2': 2, '3': 1} for record in residual)
    assert all(record['primitive_row']['coefficients'] == [2557, -2557]
               for record in residual)
    assert all(record['primitive_row']['pair'] in (
        [5, 79], [31, 653], [2, 3911], [31, 17321]) for record in residual)
    assert all(record['repaired_lattice_index'] == 1 for record in residual)
    assert all(record['extracted_factor'] == 20323 for record in residual)

    return {
        'scope': (
            'Finite second-cycle v2=3 check: half-order differences alone '
            'leave four residual index-two lattices; primitive layer-three '
            'differences, odd multiples of the top-level unit-aligned rows, '
            'repair them and extract a factor. The two-primary saturation '
            'theorem supplies the general depth/pair selection; no cost or '
            'complete-bound claim.'),
        'integer': INTEGER,
        'factorization': list(FACTORIZATION),
        'discriminant': delta,
        'cutoff': CUTOFF,
        'base_prime': BASE_PRIME,
        'period': period,
        'period_factorization': [1 << v2_period, period >> v2_period],
        'v2_period': v2_period,
        'window': WINDOW,
        'target_limit': TARGET_LIMIT,
        'base_primes': list(base_primes),
        'base_logs': {str(prime): logs[prime] for prime in base_primes},
        'targets_scanned': sum(counts.values()),
        'lattice_index_counts': {
            str(value): counts[value] for value in sorted(counts)},
        'rank_failures': failures,
        'half_order_still_index_two': sum(
            1 for record in residual
            if record['half_order_lattice_index'] % 2 == 0),
        'primitive_repairs': len(residual),
        'residual_targets': residual,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', required=True)
    arguments = parser.parse_args()
    result = run()
    with open(arguments.output, 'w') as handle:
        json.dump(result, handle, indent=2, sort_keys=True)
        handle.write('\n')
    print(json.dumps({
        'targets_scanned': result['targets_scanned'],
        'lattice_index_counts': result['lattice_index_counts'],
        'residual_targets': [record['target']
                             for record in result['residual_targets']],
        'primitive_pairs': [record['primitive_row']['pair']
                            for record in result['residual_targets']],
        'extracted_factors': [record['extracted_factor']
                              for record in result['residual_targets']],
    }, indent=2, sort_keys=True))


if __name__ == '__main__':
    main()
