"""Quadratic-form composition and supplied-word norms via two-dimensional HNF.

All loops have polynomial bit cost in the written input/output sizes.
This module performs no search for a class-group relation or smooth norm.
"""

from dataclasses import dataclass
from math import gcd, isqrt


@dataclass(frozen=True)
class IdealBasis:
    """Columns (a, 0), (r, d) in the basis (1, omega), 0 <= r < a."""
    a: int
    r: int
    d: int

    @property
    def norm(self):
        return self.a * self.d


@dataclass(frozen=True)
class NormRepresentation:
    form: tuple
    vector: tuple
    norm: int
    product_norm: int
    removed_integer_content: int


def extended_gcd(left, right):
    old_r, r, old_s, s, old_t, t = left, right, 1, 0, 0, 1
    while r:
        quotient = old_r // r
        old_r, r = r, old_r - quotient * r
        old_s, s = s, old_s - quotient * s
        old_t, t = t, old_t - quotient * t
    if old_r < 0:
        old_r, old_s, old_t = -old_r, -old_s, -old_t
    return old_r, old_s, old_t


def lattice_hnf(vectors):
    """HNF of a full-rank integer lattice generated by a fixed-size list."""
    vectors = tuple(vectors)
    second_gcd, companion = 0, 0
    for first, second in vectors:
        new_gcd, left, right = extended_gcd(second_gcd, second)
        companion = left * companion + right * first
        second_gcd = new_gcd
    determinant_gcd = 0
    for index, (first, second) in enumerate(vectors):
        for other_first, other_second in vectors[index + 1:]:
            determinant_gcd = gcd(
                determinant_gcd,
                first * other_second - second * other_first,
            )
    if not second_gcd or not determinant_gcd:
        raise ValueError("lattice must have rank two")
    if determinant_gcd % second_gcd:
        raise ArithmeticError("invalid lattice determinant")
    first = determinant_gcd // second_gcd
    return IdealBasis(first, companion % first, second_gcd)


def _discriminant_data(discriminant):
    if discriminant >= 0 or discriminant % 4 not in (0, 1):
        raise ValueError("expected a negative quadratic-order discriminant")
    parity = discriminant % 2
    return parity, (discriminant - parity) // 4


def form_to_ideal(form):
    a, b, c = form
    discriminant = b * b - 4 * a * c
    parity, _ = _discriminant_data(discriminant)
    if a <= 0 or gcd(gcd(a, b), c) != 1:
        raise ValueError("expected a primitive positive definite form")
    return IdealBasis(a, (-(b + parity) // 2) % a, 1)


def multiply_ideals(left, right, discriminant):
    parity, constant = _discriminant_data(discriminant)
    left_vectors = ((left.a, 0), (left.r, left.d))
    right_vectors = ((right.a, 0), (right.r, right.d))
    products = []
    for first, second in left_vectors:
        for other_first, other_second in right_vectors:
            products.append((
                first * other_first + constant * second * other_second,
                first * other_second + second * other_first + parity * second * other_second,
            ))
    return lattice_hnf(products)


def primitive_ideal(ideal):
    """Remove the largest positive rational-integer ideal factor."""
    if ideal.a % ideal.d or ideal.r % ideal.d:
        raise ValueError("basis is not closed under multiplication by omega")
    return IdealBasis(ideal.a // ideal.d, ideal.r // ideal.d, 1)


def ideal_to_form(ideal, discriminant):
    parity, _ = _discriminant_data(discriminant)
    ideal = primitive_ideal(ideal)
    middle = -2 * ideal.r - parity
    numerator = middle * middle - discriminant
    if numerator % (4 * ideal.a):
        raise ValueError("basis does not define an integral quadratic ideal")
    result = (ideal.a, middle, numerator // (4 * ideal.a))
    if gcd(gcd(result[0], result[1]), result[2]) != 1:
        raise ValueError("ideal is not proper invertible")
    return result


def reduce_with_transform(form):
    """Return Q, S with Q(z) = form(S z) and det(S) = 1."""
    a, b, c = form
    discriminant = b * b - 4 * a * c
    _discriminant_data(discriminant)
    if a <= 0 or gcd(gcd(a, b), c) != 1:
        raise ValueError("expected a primitive positive definite form")
    s00, s01, s10, s11 = 1, 0, 0, 1
    while True:
        shift = (a - b) // (2 * a)
        c, b = c + b * shift + a * shift * shift, b + 2 * a * shift
        s01, s11 = s00 * shift + s01, s10 * shift + s11
        if a > c or (a == c and b < 0):
            a, b, c = c, -b, a
            s00, s01, s10, s11 = s01, -s00, s11, -s10
            continue
        assert s00 * s11 - s01 * s10 == 1
        assert b * b - 4 * a * c == discriminant
        assert -a < b <= a <= c
        return (a, b, c), ((s00, s01), (s10, s11))


def compose_forms_hnf(left, right):
    discriminant = left[1] ** 2 - 4 * left[0] * left[2]
    if right[1] ** 2 - 4 * right[0] * right[2] != discriminant:
        raise ValueError("forms must have the same discriminant")
    product = multiply_ideals(form_to_ideal(left), form_to_ideal(right), discriminant)
    return reduce_with_transform(ideal_to_form(product, discriminant))[0]


def primitive_ideal_power(ideal, exponent, discriminant):
    if exponent < 0:
        raise ValueError("ideal exponent must be nonnegative")
    result = IdealBasis(1, 0, 1)
    while exponent:
        if exponent & 1:
            result = primitive_ideal(multiply_ideals(result, ideal, discriminant))
        exponent >>= 1
        if exponent:
            ideal = primitive_ideal(multiply_ideals(ideal, ideal, discriminant))
    return result


def represented_norm_from_word(discriminant, prime_terms):
    """Return an actual primitive represented norm for a supplied prime word.

    Each term is (p, exponent, root), with root^2 = discriminant mod 4p.
    The prime p and this congruence are part of the caller's factor-base
    data; primality is not searched for here. A negative exponent means
    the conjugate orientation. The norm is at most product p^|exponent|.
    """
    _discriminant_data(discriminant)
    result = IdealBasis(1, 0, 1)
    product_norm = 1
    for prime, exponent, root in prime_terms:
        if prime < 2 or gcd(prime, discriminant) != 1:
            raise ValueError("prime norm must be coprime to the discriminant")
        if (root * root - discriminant) % (4 * prime):
            raise ValueError("invalid prime-form orientation")
        if exponent < 0:
            root = -root
        base = form_to_ideal((prime, root, (root * root - discriminant) // (4 * prime)))
        product_norm *= prime ** abs(exponent)
        powered = primitive_ideal_power(base, abs(exponent), discriminant)
        result = primitive_ideal(multiply_ideals(result, powered, discriminant))
    raw_form = ideal_to_form(result, discriminant)
    reduced, matrix = reduce_with_transform(raw_form)
    vector = (matrix[1][1], -matrix[1][0])
    assert gcd(*vector) == 1
    norm = raw_form[0]
    a, b, c = reduced
    x, y = vector
    assert a * x * x + b * x * y + c * y * y == norm
    assert product_norm % norm == 0
    content = isqrt(product_norm // norm)
    assert content * content * norm == product_norm
    return NormRepresentation(reduced, vector, norm, product_norm, content)
