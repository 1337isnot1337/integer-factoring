CAP = 250_000
CAP_COFACTOR = 1


def ceil_root(integer: int, degree: int) -> int:
    if integer < 0 or degree < 1:
        raise ValueError("Require a nonnegative integer and positive degree")
    if integer <= 1:
        return integer
    low, high = 0, 1
    while high ** degree < integer:
        high *= 2
    while high - low > 1:
        middle = (low + high) // 2
        if middle ** degree >= integer:
            high = middle
        else:
            low = middle
    assert (high - 1) ** degree < integer <= high ** degree
    return high


def complete_cycle(integer: int, cutoff: int, prime: int) -> dict:
    """Enumerate one full cyclic subgroup and return its exact flags."""
    delta = -integer if integer % 4 == 3 else -4 * integer
    height = isqrt(abs(delta) // 3)
    base = build_prime_form_factor_base(delta, cutoff)
    records = {item.prime: (item.root, item.positive) for item in base["records"]}
    if prime not in records:
        raise ValueError(f"Prime {prime} is not in the split base at cutoff {cutoff}")
    prime_product = prod(records)
    identity = (1, delta % 2, (delta % 2 - delta) // 4)
    current = identity
    flags = bytearray()
    gcd_hits = 0
    for step in range(1, CAP + 1):
        leading = current[0]
        divisor = gcd(leading, integer)
        proper_gcd = 1 < divisor < integer
        gcd_hits += proper_gcd
        if leading == 1:
            smooth = True
        else:
            residue = gcd(leading, pow(prime_product, leading.bit_length(), leading))
            smooth = residue == leading
        flags.append(int(proper_gcd or smooth))
        current = compose_with_prime_form(current, prime, *records[prime])
        if current == identity:
            break
    else:
        raise RuntimeError(f"Cycle for N={integer}, p={prime} did not close in {CAP} steps")
    flags = bytes(flags)
    period = len(flags)
    assert period == step
    assert flags[0] == 1
    assert period <= 2 * integer, "Input-only period bound failed"
    assert all(flags[index] == flags[-index] for index in range(period))
    return {
        "integer": integer,
        "input_bits": integer.bit_length(),
        "discriminant": delta,
        "cutoff": cutoff,
        "height": height,
        "generator_prime": prime,
        "least_power_above_height": least_power_above(prime, height),
        "prime_form": list(records[prime][1]),
        "prime_root": records[prime][0],
        "prime_product": prime_product,
        "period": period,
        "identity_reached": True,
        "leading_gcd_hits": gcd_hits,
        "flags": flags,
        "flags_sha256": hashlib.sha256(flags).hexdigest(),
        "inverse_symmetry_checked": True,
    }


def entry_flags(flags: bytes) -> bytes:
    period = len(flags)
    return bytes(flags[index] * (1 - flags[index - 1]) for index in range(period))


def cyclic_window_counts(flags: bytes, window: int) -> list[int]:
    period, good = len(flags), sum(flags)
    whole, remainder = divmod(window, period)
    current = whole * good + sum(flags[:remainder])
    counts = []
    for phase in range(period):
        counts.append(current)
        current += flags[(phase + remainder) % period] - flags[phase]
    assert sum(counts) == good * window
    return counts


def lower_tail_record(flags: bytes, window: int, order: int, constant: int) -> dict:
    """Exact check of (1/h) sum (mu-A)_+^{2q} <= (C q W delta)^q."""
    period, good = len(flags), sum(flags)
    counts = cyclic_window_counts(flags, window)
    deviations = [good * window - period * count for count in counts]
    lower = sum((-value) ** (2 * order) for value in deviations if value < 0)
    # lower <= (C q W good)^q * period^(q+1)
    unit_rhs = (order * window * good) ** order * period ** (order + 1)
    assert lower >= 0 and unit_rhs >= 1
    rhs = constant ** order * unit_rhs
    empty = sum(1 for count in counts if count == 0)
    return {
        "window": window,
        "moment_order": order,
        "constant": constant,
        "minimum_hits": min(counts),
        "maximum_hits": max(counts),
        "empty_windows": empty,
        "lower_tail_numerator": lower,
        "moment_rhs": rhs,
        "moment_bound_holds": lower <= rhs,
    }


def required_constant(flags: bytes, window: int, order: int) -> float:
    period, good = len(flags), sum(flags)
    counts = cyclic_window_counts(flags, window)
    deviations = [good * window - period * count for count in counts]
    lower = sum((-value) ** (2 * order) for value in deviations if value < 0)
    if lower == 0:
        return 0.0
    # C^q = lower / ((q W good)^q period^(q+1)).
    log10_cq = (math.log10(lower) - order * math.log10(order * window * good)
                - (order + 1) * math.log10(period))
    return 10.0 ** (log10_cq / order)


def sufficient_window(flags: bytes, order: int, constant: int, period_bound: int) -> int:
    period, good = len(flags), sum(flags)
    denominator = (period + good - 1) // good
    threshold = (2 * order + 1) * (constant * order) ** order * period_bound
    return denominator * (ceil_root(threshold, order + 1) + 1)


def start_record(flags: bytes, window: int, phase: int) -> dict:
    period = len(flags)
    count = sum(flags[(phase + offset) % period] for offset in range(window))
    return {"window": window, "start_phase": phase,
            "window_hits": count, "window_empty": count == 0}


def profile_cycle(record: dict) -> dict:
    flags = record.pop("flags")
    other_phase = None
    if "derived_other_generator" in record:
        other_phase = record["derived_other_generator"]["actual_start_phase"]
    period, good = len(flags), sum(flags)
    entries = entry_flags(flags)
    entry_count = sum(entries)
    run_count = sum(flags[index] * (1 - flags[index - 1]) for index in range(period))
    assert entry_count == run_count
    assert all(entry <= hit for entry, hit in zip(entries, flags))
    assert sum(1 for index in range(period)
               if flags[index] and not flags[index - 1]) == entry_count
    assert good * period == sum(flags) * period
    mean_run = good / entry_count
    assert abs(entry_count / period - (good / period) / mean_run) < 1e-15
    order = (record["input_bits"] + 1).bit_length()
    orders = sorted({order, order * order})
    start = record["least_power_above_height"]
    record.update({
        "density": {"good_classes": good, "period": period,
                    "decimal": good / period},
        "entry": {"entries": entry_count, "density_decimal": entry_count / period,
                  "mean_hit_run_decimal": mean_run,
                  "mean_run_times_entry_density_check": True,
                  "entry_flags_sha256": hashlib.sha256(entries).hexdigest()},
        "entry_containment_checked": True,
    })
    processes = {"raw": flags, "entry": entries}
    sufficient = []
    matched = []
    for name, process_flags in processes.items():
        process_good = sum(process_flags)
        process_density = process_good / period
        for moment_order in orders:
            for constant in (1, 2):
                window = sufficient_window(process_flags, moment_order, constant, 2 * record["integer"])
                item = {"process": name, "moment_order": moment_order,
                        "constant": constant, "window": window,
                        "wraps_period": window >= period}
                if not item["wraps_period"]:
                    check = lower_tail_record(process_flags, window, moment_order, constant)
                    check.update({"process": name, "required_constant_decimal":
                                  required_constant(process_flags, window, moment_order),
                                  "start": start_record(process_flags, window, start)})
                    if other_phase is not None:
                        check["start_derived_other"] = start_record(
                            process_flags, window, other_phase)
                    item["lower_tail"] = check
                sufficient.append(item)
        for multiple in (1, 2, 4, 8):
            window = max(1, math.ceil(multiple / process_density))
            for moment_order in orders:
                check = lower_tail_record(process_flags, window, moment_order, 1)
                check2 = lower_tail_record(process_flags, window, moment_order, 2)
                matched.append({
                    "process": name, "mean_multiple": multiple, "window": window,
                    "moment_order": moment_order,
                    "empty_fraction_decimal": check["empty_windows"] / period,
                    "minimum_hits": check["minimum_hits"],
                    "maximum_hits": check["maximum_hits"],
                    "constant_one_bound_holds": check["moment_bound_holds"],
                    "constant_two_bound_holds": check2["moment_bound_holds"],
                    "required_constant_decimal": required_constant(process_flags, window, moment_order),
                    "start": start_record(process_flags, window, start),
                    **({"start_derived_other": start_record(
                        process_flags, window, other_phase)}
                       if other_phase is not None else {}),
                })
    record["moment_parameters"] = {
        "orders": orders,
        "order_definition": "bit_length(input_bits + 1) and its square",
        "period_bound": 2 * record["integer"],
        "period_bound_is_input_only": True,
        "constants": [1, 2],
        "matched_mean_multiples": [1, 2, 4, 8],
        "matched_window_convention": "ceil(multiple/density)",
    }
    record["sufficient_windows"] = sufficient
    record["matched_mean_windows"] = matched
    record["actual_start"] = {"phase": start,
                              "flag": flags[start],
                              "first_hit_offset": next((offset for offset in range(period)
                                                        if flags[(start + offset) % period]), None)}
    if other_phase is not None:
        record["derived_other_generator"]["flag"] = flags[other_phase]
        record["derived_other_generator"]["first_hit_offset"] = next(
            (offset for offset in range(period)
             if flags[(other_phase + offset) % period]), None)
    return record


def g7_index(integer: int, cutoff: int, generator: int, other: int,
             period: int) -> dict:
    """Find the exact discrete index of the other prime form in the cycle."""
    delta = -integer if integer % 4 == 3 else -4 * integer
    base = build_prime_form_factor_base(delta, cutoff)
    records = {item.prime: (item.root, item.positive) for item in base["records"]}
    identity = (1, delta % 2, (delta % 2 - delta) // 4)
    current, index = identity, None
    target = records[other][1]
    for exponent in range(period):
        if current == target:
            index = exponent
            break
        current = compose_with_prime_form(current, generator, *records[generator])
    if index is None:
        raise RuntimeError("Other prime form is not in the enumerated cycle")
    height = isqrt(abs(delta) // 3)
    k_other = least_power_above(other, height)
    phase = (index * k_other) % period
    return {"prime": other, "discrete_index": index,
            "least_power_above_height": k_other,
            "actual_start_phase": phase,
            "prime_form": list(target)}


def replay(expected_path: Path) -> None:
    expected = json.loads(expected_path.read_text())
    for cycle in expected["cycles"]:
        if "derived_other_generator" in cycle:
            other = cycle["derived_other_generator"]["prime"]
        else:
            other = None
        record = complete_cycle(cycle["integer"], cycle["cutoff"],
                                cycle["generator_prime"])
        if other is not None:
            record["derived_other_generator"] = g7_index(
                cycle["integer"], cycle["cutoff"], cycle["generator_prime"],
                other, record["period"])
        record = profile_cycle(record)
        assert record == cycle, f"Replay mismatch for N={cycle['integer']}"


